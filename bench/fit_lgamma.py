"""Fit the Chebyshev interpolant of g(x) = lgamma(x) / ((x - 1)(x - 2)) on [A, B] = [0.75, 3].

All arithmetic is in 40+ digit Decimal (bench/hiprec_ref.py), so the float64 coefficients are
correctly rounded. Writes pytensor_mojo/_lgamma_cheb.py.
Usage: python bench/fit_lgamma.py [--n 48] [--check]
"""
import argparse, pathlib, sys
from decimal import Decimal, getcontext

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "bench"))
import hiprec_ref as hp  # noqa: E402

getcontext().prec = 50
A, B = Decimal("0.75"), Decimal(3)


def g(x: Decimal) -> Decimal:
    return hp._lgamma_dec_pos(x) / ((x - 1) * (x - 2))


def cheb_coefs(n: int):
    half, mid = (B - A) / 2, (A + B) / 2
    nodes = []
    for k in range(n):
        _, ck = hp._sincos_pi(Decimal(2 * k + 1) / (2 * n))
        nodes.append(mid + half * ck)
    gv = [g(x) for x in nodes]
    cs = []
    for j in range(n):
        s = Decimal(0)
        for k in range(n):
            _, c = hp._sincos_pi(Decimal(j * (2 * k + 1)) / (2 * n))
            s += gv[k] * c
        cs.append(s * 2 / n)
    cs[0] /= 2
    return cs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=48)
    ap.add_argument("--keep", type=float, default=1e-20, help="drop trailing coefficients below this")
    a = ap.parse_args()
    cs = cheb_coefs(a.n)
    keep = max(j for j, c in enumerate(cs) if abs(c) > Decimal(a.keep)) + 1
    print("coefficient magnitudes:", ", ".join(f"{float(abs(c)):.1e}" for c in cs[::4]))
    print(f"keeping {keep} of {a.n} (|c_j| > {a.keep})")
    out = ROOT / "pytensor_mojo" / "_lgamma_cheb.py"
    body = ",\n    ".join(repr(float(c)) for c in cs[:keep])
    out.write_text('"""Chebyshev coefficients of lgamma(x) / ((x - 1)(x - 2)) on [CHEB_A, CHEB_B].\n\n'
                   'Generated by bench/fit_lgamma.py from a 40-digit Decimal reference; do not edit.\n"""\n'
                   f"CHEB_A = {float(A)!r}\nCHEB_B = {float(B)!r}\nCHEB_COEFS = [\n    {body},\n]\n")
    print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
