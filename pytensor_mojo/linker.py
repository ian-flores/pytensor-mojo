"""Toy PyTensor -> Mojo backend (feasibility prototype).

Supported subset (enough for the eight-schools logp+dlogp graph):
  * variables of ndim 0 or 1, float64 (bool only inside Composite), static 1-D lengths
  * Elemwise with any scalar op in SCALAR_OPS, including (nested) Composite
  * Sum{axes=None} (CAReduce with scalar Add over all axes)
  * DimShuffle that only adds or drops broadcastable dims between 0-D and (1,)

Codegen strategy: one Mojo function per FunctionGraph. Every array (inputs,
non-scalar constants, intermediates, outputs) lives in a NumPy buffer owned by
the Python wrapper; their addresses are packed into a single int64 table, so
each call crosses the Python->Mojo boundary with exactly one argument.
"""
from __future__ import annotations

import hashlib
import importlib.util
import math
import os
import pathlib
import subprocess
import sys

import numpy as np
from pytensor.compile.mode import Mode
from pytensor.graph.basic import Constant
from pytensor.graph.rewriting.db import RewriteDatabaseQuery
from pytensor.link.basic import JITLinker
from pytensor.scalar import basic as ps
from pytensor.tensor.elemwise import CAReduce, DimShuffle, Elemwise
from pytensor.tensor.math import Sum

CACHE_DIR = pathlib.Path(os.environ.get("PYTENSOR_MOJO_CACHE", pathlib.Path(__file__).parent / "__mojocache__"))


def _lit(v) -> str:
    v = float(v)
    if math.isnan(v):
        return "NAN"
    if math.isinf(v):
        return "POS_INF" if v > 0 else "NEG_INF"
    return f"Float64({v!r})"


def _nary(sym):
    return lambda *a: "(" + f" {sym} ".join(a) + ")"


SCALAR_OPS = {
    ps.Add: _nary("+"),
    ps.Mul: _nary("*"),
    ps.Sub: lambda a, b: f"({a} - {b})",
    ps.TrueDiv: lambda a, b: f"({a} / {b})",
    ps.Neg: lambda a: f"(-{a})",
    ps.Sqr: lambda a: f"({a} * {a})",
    ps.Sqrt: lambda a: f"sqrt({a})",
    ps.Exp: lambda a: f"_exp({a})",
    ps.Log: lambda a: f"log({a})",
    ps.Log1p: lambda a: f"log1p({a})",
    ps.Reciprocal: lambda a: f"(Float64(1.0) / {a})",
    ps.Identity: lambda a: a,
    ps.GE: lambda a, b: f"({a} >= {b})",
    ps.GT: lambda a, b: f"({a} > {b})",
    ps.LE: lambda a, b: f"({a} <= {b})",
    ps.LT: lambda a, b: f"({a} < {b})",
    ps.EQ: lambda a, b: f"({a} == {b})",
    ps.NEQ: lambda a, b: f"({a} != {b})",
    ps.AND: lambda a, b: f"({a} and {b})",
    ps.OR: lambda a, b: f"({a} or {b})",
    ps.Switch: lambda c, a, b: f"({a} if {c} else {b})",
}

HEADER = '''# Generated by pytensor_mojo.linker -- do not edit.
from std.python import PythonObject
from std.python.bindings import PythonModuleBuilder
from std.os import abort
from std.math import log, log1p, sqrt
from std.ffi import external_call

comptime POS_INF = Float64(1.0) / Float64(0.0)
comptime NEG_INF = Float64(-1.0) / Float64(0.0)
comptime NAN = Float64(0.0) / Float64(0.0)


@always_inline
def _exp(x: Float64) -> Float64:
    return external_call["exp", Float64](x)


@always_inline
def _buf(tab: Pointer[Int64, MutAnyOrigin], k: Int) -> Pointer[Float64, MutAnyOrigin]:
    return Pointer[Float64, MutAnyOrigin](unsafe_from_address=Int(tab[unsafe_offset=k]))


@export
def PyInit_{mod}() abi("C") -> PythonObject:
    try:
        var m = PythonModuleBuilder("{mod}")
        m.def_function[run]("run")
        return m.finalize()
    except e:
        abort(String("error creating {mod}:", e))


def run(tab_addr: PythonObject) raises -> PythonObject:
    var tab = tab_addr.unsafe_get_as_pointer[DType.int64]()
'''


class _Codegen:
    def __init__(self, fgraph):
        self.fgraph = fgraph
        self.lines: list[str] = []
        self.buffers: list[tuple[str, object]] = []  # (role, payload) in table order
        self.scalar_name: dict = {}   # var -> Mojo scalar expr (0-D values and (1,) aliases)
        self.buf_name: dict = {}      # var -> (pointer name, length)
        self.n = 0

    def fresh(self, p):
        self.n += 1
        return f"{p}{self.n}"

    def emit(self, s, indent=1):
        self.lines.append("    " * indent + s)

    @staticmethod
    def _check_type(v):
        if v.type.ndim > 1:
            raise NotImplementedError(f"ndim>1 not supported: {v}")
        if v.type.dtype != "float64":
            raise NotImplementedError(f"dtype {v.type.dtype} not supported: {v}")
        if v.type.ndim == 1 and v.type.shape[0] is None:
            raise NotImplementedError(f"static 1-D length required: {v}")

    def new_buffer(self, v, role, payload=None):
        k = len(self.buffers)
        self.buffers.append((role, payload if payload is not None else v))
        name = f"b{k}"
        self.emit(f"var {name} = _buf(tab, {k})")
        return name

    def bind_input(self, v, role, payload=None):
        self._check_type(v)
        name = self.new_buffer(v, role, payload)
        if v.type.ndim == 0:
            s = self.fresh("s")
            self.emit(f"var {s} = {name}[unsafe_offset=0]")
            self.scalar_name[v] = s
        else:
            self.buf_name[v] = (name, v.type.shape[0])

    def elem(self, v, i):
        if v in self.scalar_name:
            return self.scalar_name[v]
        name, n = self.buf_name[v]
        return f"{name}[unsafe_offset=0]" if n == 1 else f"{name}[unsafe_offset={i}]"

    def ensure(self, v):
        if v in self.scalar_name or v in self.buf_name:
            return
        if isinstance(v, Constant):
            if v.type.ndim == 0:
                self.scalar_name[v] = _lit(v.data)
            else:
                self.bind_input(v, "const", np.ascontiguousarray(v.data, dtype=np.float64))
            return
        raise RuntimeError(f"variable not yet computed: {v}")

    # --- scalar (Composite) inlining -------------------------------------
    def scalar_expr(self, sop, args, indent):
        if isinstance(sop, ps.Composite):
            env = dict(zip(sop.fgraph.inputs, args))
            for node in sop.fgraph.toposort():
                ins = []
                for x in node.inputs:
                    if x in env:
                        ins.append(env[x])
                    elif isinstance(x, ps.ScalarConstant):
                        ins.append("True" if x.type.dtype == "bool" and x.data else _lit(x.data))
                    else:
                        raise RuntimeError(x)
                outs = self.scalar_expr(node.op, ins, indent)
                for o, e in zip(node.outputs, outs):
                    t = self.fresh("t")
                    self.emit(f"var {t} = {e}", indent)
                    env[o] = t
            return [env[o] for o in sop.fgraph.outputs]
        fn = SCALAR_OPS.get(type(sop))
        if fn is None:
            raise NotImplementedError(f"scalar op {type(sop).__name__}")
        return [fn(*args)]

    # --- tensor ops ------------------------------------------------------
    def node(self, node):
        op = node.op
        for x in node.inputs:
            self.ensure(x)
        for o in node.outputs:
            self._check_type(o)
        if isinstance(op, Elemwise):
            return self.elemwise(node)
        if isinstance(op, Sum) or (isinstance(op, CAReduce) and isinstance(op.scalar_op, ps.Add)):
            return self.sum_all(node)
        if isinstance(op, DimShuffle):
            return self.dimshuffle(node)
        raise NotImplementedError(f"op {op}")

    def elemwise(self, node):
        out = node.outputs
        nd = out[0].type.ndim
        n = out[0].type.shape[0] if nd == 1 else 1
        if nd == 0:
            res = self.scalar_expr(node.op.scalar_op, [self.elem(x, "0") for x in node.inputs], 1)
            for o, e in zip(out, res):
                s = self.fresh("s")
                self.emit(f"var {s} = {e}")
                self.scalar_name[o] = s
            return
        names = []
        for o in out:
            b = self.new_buffer(o, "work")
            self.buf_name[o] = (b, n)
            names.append(b)
        self.emit(f"for i in range({n}):")
        res = self.scalar_expr(node.op.scalar_op, [self.elem(x, "i") for x in node.inputs], 2)
        for b, e in zip(names, res):
            self.emit(f"{b}[unsafe_offset=i] = {e}", 2)

    def sum_all(self, node):
        (x,), (o,) = node.inputs, node.outputs
        if o.type.ndim != 0:
            raise NotImplementedError("only full reductions")
        if x.type.ndim == 0 or x in self.scalar_name:
            self.scalar_name[o] = self.elem(x, "0")
            return
        s = self.fresh("s")
        b, n = self.buf_name[x]
        self.emit(f"var {s} = Float64(0)")
        self.emit(f"for i in range({n}):")
        self.emit(f"{s} += {b}[unsafe_offset=i]", 2)
        self.scalar_name[o] = s

    def dimshuffle(self, node):
        (x,), (o,) = node.inputs, node.outputs
        # Only 0-D <-> (1,) reshapes: alias to the scalar value.
        if o.type.ndim == 1 and o.type.shape[0] != 1 or x.type.ndim == 1 and x.type.shape[0] != 1:
            raise NotImplementedError(f"general DimShuffle {node.op}")
        self.scalar_name[o] = self.elem(x, "0")

    def generate(self):
        for v in self.fgraph.inputs:
            self.bind_input(v, "input")
        for node in self.fgraph.toposort():
            self.node(node)
        self.out_slots = []
        for o in self.fgraph.outputs:
            self.ensure(o)
            self._check_type(o)
            if o in self.buf_name:
                b, n = self.buf_name[o]
                self.out_slots.append(("buf", self.buffers_index(b), n))
            else:
                b = self.new_buffer(o, "out_scalar")
                self.emit(f"{b}[unsafe_offset=0] = {self.scalar_name[o]}")
                self.out_slots.append(("scalar", int(b[1:]), 0))
        self.emit("return PythonObject(None)")
        return "\n".join(self.lines) + "\n"

    def buffers_index(self, name):
        return int(name[1:])


def build_module(src: str, mod: str):
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    so = CACHE_DIR / f"{mod}.so"
    if not so.exists():
        srcf = CACHE_DIR / f"{mod}.mojo"
        srcf.write_text(src)
        r = subprocess.run(["mojo", "build", str(srcf), "--emit", "shared-lib", "-o", str(so)],
                           capture_output=True, text=True)
        if r.returncode != 0 or not so.exists():
            raise RuntimeError(f"mojo build failed:\n{r.stdout}\n{r.stderr}")
    spec = importlib.util.spec_from_file_location(mod, so)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    sys.modules[mod] = m
    return m


def mojo_funcify(fgraph):
    cg = _Codegen(fgraph)
    body = cg.generate()
    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    mod = f"mj_{digest}"
    src = HEADER.replace("{mod}", mod) + body
    m = build_module(src, mod)

    # Allocate every buffer once; inputs are written into their buffers per call.
    bufs = []
    for role, payload in cg.buffers:
        if role == "const":
            bufs.append(payload)
        else:
            v = payload
            bufs.append(np.zeros(v.type.shape if v.type.ndim else (1,), dtype=np.float64))
    tab = np.array([b.ctypes.data for b in bufs], dtype=np.int64)
    tab_addr = tab.ctypes.data
    in_bufs = [bufs[k] for k, (role, _) in enumerate(cg.buffers) if role == "input"]
    out_slots = cg.out_slots
    run = m.run

    def fn(*inputs):
        for b, x in zip(in_bufs, inputs):
            b[...] = np.reshape(x, b.shape)
        run(tab_addr)
        return [np.array(bufs[k][0]) if kind == "scalar" else bufs[k].copy() for kind, k, _ in out_slots]

    fn.mojo_source = src
    fn.mojo_module = m
    fn._keepalive = (bufs, tab)
    return fn


class MojoLinker(JITLinker):
    """A JITLinker that turns a FunctionGraph into one generated Mojo function."""

    required_rewrites = ("minimum_compile",)
    incompatible_rewrites = ("cxx_only", "BlasOpt", "inplace", "numba")

    def fgraph_convert(self, fgraph, **kwargs):
        return mojo_funcify(fgraph)

    def jit_compile(self, fn):
        return fn

    def create_thunk_inputs(self, storage_map):
        return [storage_map[n] for n in self.fgraph.inputs]


MOJO = Mode(
    MojoLinker(),
    RewriteDatabaseQuery(include=["fast_run"], exclude=["cxx_only", "BlasOpt", "inplace", "numba"]),
)
