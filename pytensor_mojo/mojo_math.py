"""Vectorized float64 transcendentals for generated Mojo code (Phase 7).

The Mojo prelude below implements SIMD versions of exp, log, log1p, expm1 and lgamma that
work on ``SIMD[DType.float64, w]`` lane-parallel, so fused loops do not fall back to one
libm call per lane.

Algorithms (all branch-free; special cases are handled with ``select``):

* exp, log, log1p, expm1 follow the fdlibm (Sun Microsystems, freely distributable)
  algorithms and coefficients: Cody-Waite reduction by ln 2 with a split constant, then
  fdlibm's Remez-minimax kernels (exp: rational form ``1 - ((lo - r c / (2 - c)) - hi)``;
  log / log1p: ``s = f / (2 + f)`` with the Lg1..Lg7 polynomial; expm1: the Q1..Q5 kernel
  with its correction terms), reconstructed with an exact power of two built from the bits.
  fdlibm documents errors below 1 ulp for all four.
* lgamma (x > 0): ``(x - 1)(x - 2) g(x)`` on [0.75, 3], with g a Chebyshev interpolant
  fitted against a 40-digit reference (keeps relative accuracy at the zeros x = 1, 2);
  ``lgamma(x + 1) - log(x)`` below 0.75; upward recurrence sums of logs on (3, 12);
  Stirling's series with the ``(x - 1/2)(log x - 1)`` form above 12. Non-positive lanes
  fall back to libm ``lgamma_r``.

``PYTENSOR_MOJO_LIBM=1`` switches all of these back to per-lane libm calls.
"""
from __future__ import annotations

import os

LIBM = os.environ.get("PYTENSOR_MOJO_LIBM", "0") == "1"

# Chebyshev coefficients of g(x) = lgamma(x) / ((x - 1)(x - 2)) on [0.75, 3], generated by
# bench/fit_lgamma.py against the 40-digit Decimal reference (bench/hiprec_ref.py).
from ._lgamma_cheb import CHEB_A, CHEB_B, CHEB_COEFS  # noqa: E402

PRELUDE = r'''
# ---- Phase 7: vectorized transcendentals (pytensor_mojo/mojo_math.py) -------------------
from std.memory import bitcast as _bitcast

comptime _LN2_HI = 6.93147180369123816490e-01
comptime _LN2_LO = 1.90821492927058770002e-10
comptime _INVLN2 = 1.44269504088896338700e+00
comptime _SQRT2 = 1.4142135623730951
comptime _P1 = 1.66666666666666019037e-01
comptime _P2 = -2.77777777770155933842e-03
comptime _P3 = 6.61375632143793436117e-05
comptime _P4 = -1.65339022054652515390e-06
comptime _P5 = 4.13813679705723846039e-08
comptime _LG1 = 6.666666666666735130e-01
comptime _LG2 = 3.999999999940941908e-01
comptime _LG3 = 2.857142874366239149e-01
comptime _LG4 = 2.222219843214978396e-01
comptime _LG5 = 1.818357216161805012e-01
comptime _LG6 = 1.531383769920937332e-01
comptime _LG7 = 1.479819860511658591e-01
comptime _Q1 = -3.33333333333331316428e-02
comptime _Q2 = 1.58730158725481460165e-03
comptime _Q3 = -7.93650757867487942473e-05
comptime _Q4 = 4.00821782732936239552e-06
comptime _Q5 = -2.01099218183624371326e-07
comptime _EXP_OVER = 7.09782712893383973096e+02
comptime _EXP_UNDER = -7.45133219101941108420e+02


@always_inline
def _isnan[w: Int](x: SIMD[DType.float64, w]) -> SIMD[DType.bool, w]:
    # Bit test: Mojo's SIMD .ne() is an ordered compare, so x.ne(x) is False for NaN.
    comptime I = SIMD[DType.int64, w]
    return (_bitcast[DType.int64, w](x) & I(0x7FFFFFFFFFFFFFFF)).gt(I(0x7FF0000000000000))


@always_inline
def _pow2i[w: Int](k: SIMD[DType.int64, w]) -> SIMD[DType.float64, w]:
    # 2^k for k in [-1022, 1023], exact, from the exponent bits
    return _bitcast[DType.float64, w]((k + 1023) << 52)


@always_inline
def _scalbn[w: Int](y: SIMD[DType.float64, w], k: SIMD[DType.int64, w]) -> SIMD[DType.float64, w]:
    # y * 2^k with k in [-1100, 1100]: two exact factors, so subnormal results round once
    var k1 = k >> 1
    return y * _pow2i[w](k1) * _pow2i[w](k - k1)


@always_inline
def sexp[w: Int](x: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    # fdlibm e_exp: Cody-Waite reduction, Remez rational kernel, exact 2^k reconstruction.
    # (A division-free degree-13 Taylor kernel was measured: same accuracy, 13% slower.)
    comptime F = SIMD[DType.float64, w]
    var kf = round(x * F(_INVLN2))
    var k = kf.cast[DType.int64]()
    var hi = x - kf * F(_LN2_HI)          # exact: _LN2_HI has trailing zero bits
    var lo = kf * F(_LN2_LO)
    var r = hi - lo
    var t = r * r
    var c = r - t * (F(_P1) + t * (F(_P2) + t * (F(_P3) + t * (F(_P4) + t * F(_P5)))))
    var y = F(1) - ((lo - (r * c) / (F(2) - c)) - hi)
    var res = _scalbn[w](y, k)
    res = x.gt(F(_EXP_OVER)).select(F(POS_INF), res)
    res = x.lt(F(_EXP_UNDER)).select(F(0), res)
    return _isnan[w](x).select(x, res)


@always_inline
def _log_kernel[w: Int](f: SIMD[DType.float64, w], kf: SIMD[DType.float64, w],
                        c: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    # log(2^k (1 + f)) + c with sqrt(2)/2 <= 1 + f < sqrt(2) (fdlibm e_log / s_log1p)
    comptime F = SIMD[DType.float64, w]
    var s = f / (F(2) + f)
    var z = s * s
    var ww = z * z
    var t1 = ww * (F(_LG2) + ww * (F(_LG4) + ww * F(_LG6)))
    var t2 = z * (F(_LG1) + ww * (F(_LG3) + ww * (F(_LG5) + ww * F(_LG7))))
    var R = t2 + t1
    var hfsq = F(0.5) * f * f
    return kf * F(_LN2_HI) - ((hfsq - (s * (hfsq + R) + (kf * F(_LN2_LO) + c))) - f)


@always_inline
def _frexp_sqrt2[w: Int](u: SIMD[DType.float64, w]) -> Tuple[SIMD[DType.float64, w], SIMD[DType.float64, w]]:
    # u = 2^k * m with m in [sqrt(2)/2, sqrt(2)); u > 0 finite (subnormals scaled by 2^54)
    comptime F = SIMD[DType.float64, w]
    comptime I = SIMD[DType.int64, w]
    var sub = u.lt(F(2.2250738585072014e-308))
    var us = sub.select(u * F(18014398509481984.0), u)
    var bits = _bitcast[DType.int64, w](us)
    var k = ((bits >> 52) & I(0x7FF)) - I(1023) - sub.select(I(54), I(0))
    var m = _bitcast[DType.float64, w]((bits & I(0xFFFFFFFFFFFFF)) | I(0x3FF0000000000000))
    var big = m.gt(F(_SQRT2))
    m = big.select(m * F(0.5), m)
    k = k + big.select(I(1), I(0))
    return (m, k.cast[DType.float64]())


@always_inline
def slog[w: Int](x: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    comptime F = SIMD[DType.float64, w]
    var xs = x.gt(F(0)).select(x, F(1))
    var mk = _frexp_sqrt2[w](xs)
    var res = _log_kernel[w](mk[0] - F(1), mk[1], F(0))
    res = x.eq(F(POS_INF)).select(x, res)
    res = x.eq(F(0)).select(F(NEG_INF), res)
    res = x.lt(F(0)).select(F(NAN), res)
    return _isnan[w](x).select(x, res)


@always_inline
def slog1p[w: Int](x: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    comptime F = SIMD[DType.float64, w]
    var xs = (x.gt(F(-1)) & x.lt(F(POS_INF))).select(x, F(0))
    var u = F(1) + xs
    var mk = _frexp_sqrt2[w](u)
    var kf = mk[1]
    # rounding error of u = 1 + x, relative to u (fdlibm s_log1p). As in fdlibm, the choice
    # uses u's raw exponent (before the sqrt(2) renormalization): u - 1 is exact for u < 2.
    var c = u.ge(F(2)).select(F(1) - (u - xs), xs - (u - F(1))) / u
    var res = _log_kernel[w](mk[0] - F(1), kf, c)
    res = x.eq(F(POS_INF)).select(x, res)
    res = x.eq(F(-1)).select(F(NEG_INF), res)
    res = x.lt(F(-1)).select(F(NAN), res)
    return _isnan[w](x).select(x, res)


@always_inline
def sexpm1[w: Int](x0: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    # fdlibm s_expm1, all branches evaluated and selected
    comptime F = SIMD[DType.float64, w]
    comptime I = SIMD[DType.int64, w]
    var x = (_isnan[w](x0) | x0.gt(F(_EXP_OVER))).select(F(0), x0)
    var small = abs(x).le(F(0.5 * 0.6931471805599453))
    var kf = small.select(F(0), round(x * F(_INVLN2)))
    var hi = x - kf * F(_LN2_HI)
    var lo = kf * F(_LN2_LO)
    var xr = hi - lo
    var c = (hi - xr) - lo
    var k = kf.cast[DType.int64]()
    var hfx = F(0.5) * xr
    var hxs = xr * hfx
    var r1 = F(1) + hxs * (F(_Q1) + hxs * (F(_Q2) + hxs * (F(_Q3) + hxs * (F(_Q4) + hxs * F(_Q5)))))
    var t = F(3) - r1 * hfx
    var e = hxs * ((r1 - t) / (F(6) - xr * t))
    var res0 = xr - (xr * e - hxs)                       # k == 0
    var e2 = (xr * (e - c) - c) - hxs
    var res_m1 = F(0.5) * (xr - e2) - F(0.5)             # k == -1
    var res_p1 = xr.lt(F(-0.25)).select(F(-2) * (e2 - (xr + F(0.5))), F(1) + F(2) * (xr - e2))  # k == 1
    var y_far = _scalbn[w](F(1) - (e2 - xr), k) - F(1)   # k <= -2 or k > 56
    var kc = k.lt(I(0)).select(I(0), k.gt(I(60)).select(I(60), k))
    var tk = _pow2i[w](-kc)                               # 2^-k (only used for 2 <= k <= 56)
    var y_mid_lo = _scalbn[w]((F(1) - tk) - (e2 - xr), k)            # 2 <= k < 20
    var y_mid_hi = _scalbn[w]((xr - (e2 + tk)) + F(1), k)            # 20 <= k <= 56
    var res = k.lt(I(20)).select(y_mid_lo, y_mid_hi)
    res = (k.le(I(-2)) | k.gt(I(56))).select(y_far, res)
    res = k.eq(I(1)).select(res_p1, res)
    res = k.eq(I(-1)).select(res_m1, res)
    res = k.eq(I(0)).select(res0, res)
    res = x.lt(F(-38.816242111356935)).select(F(-1), res)   # below -56 ln 2: -1 to double
    res = x0.gt(F(_EXP_OVER)).select(F(POS_INF), res)
    return _isnan[w](x0).select(x0, res)


comptime _CHEB_A = __CHEB_A__
comptime _CHEB_B = __CHEB_B__
comptime _CHEB_N = __CHEB_N__
comptime _CHEB = [__CHEB_COEFS__]
comptime _HALF_LOG_2PI = 0.91893853320467274178032973640561764


@always_inline
def _lgamma_g[w: Int](x: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    # Clenshaw evaluation of the Chebyshev interpolant of lgamma(x)/((x-1)(x-2)) on [A, B]
    comptime F = SIMD[DType.float64, w]
    var t = (F(2) * x - F(_CHEB_A + _CHEB_B)) / F(_CHEB_B - _CHEB_A)
    var t2 = F(2) * t
    var b1 = F(0)
    var b2 = F(0)
    comptime for j in range(_CHEB_N - 1, 0, -1):
        comptime cj = _CHEB[j]
        var b0 = t2.fma(b1, F(cj) - b2)
        b2 = b1
        b1 = b0
    comptime c0 = _CHEB[0]
    return t.fma(b1, F(c0) - b2)


@always_inline
def _lgamma_mid[w: Int](x: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    # x in [A, B]: (x - 1)(x - 2) g(x); x - 1 and x - 2 are exact near the zeros
    comptime F = SIMD[DType.float64, w]
    return ((x - F(1)) * (x - F(2))) * _lgamma_g[w](x)


@always_inline
def _lgamma_stirling[w: Int](x: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    # x >= 12: (x - 1/2)(log x - 1) + (1/2 log 2 pi - 1/2) + sum B_2k / (2k (2k-1) x^(2k-1))
    comptime F = SIMD[DType.float64, w]
    var r = F(1) / x
    var r2 = r * r
    var ser = r * (F(1.0 / 12.0) + r2 * (F(-1.0 / 360.0) + r2 * (F(1.0 / 1260.0) + r2 * (F(-1.0 / 1680.0)
        + r2 * (F(1.0 / 1188.0) + r2 * (F(-691.0 / 360360.0) + r2 * F(1.0 / 156.0)))))))
    var lx = slog[w](x)
    return (x - F(0.5)) * (lx - F(1)) + (F(_HALF_LOG_2PI - 0.5) + ser)


@always_inline
def slgamma[w: Int](x: SIMD[DType.float64, w]) -> SIMD[DType.float64, w]:
    comptime F = SIMD[DType.float64, w]
    # (a) x in [A, B]
    var xm = x.ge(F(_CHEB_A)).select(x.le(F(_CHEB_B)).select(x, F(_CHEB_B)), F(_CHEB_A))
    var mid = _lgamma_mid[w](xm)
    # (b) 0 < x < A: lgamma(x + 1) - log(x), with x + 1 in (1, A + 1) inside [A, B]
    var xs = x.gt(F(0)).select(x.lt(F(_CHEB_A)).select(x, F(0.5)), F(0.5))
    var low = _lgamma_mid[w](xs + F(1)) - slog[w](xs)
    # (c) B < x < 12: lgamma(x - n) + log((x-1)(x-2)...(x-n)), x - n in (B - 1, B]
    var xr = x.gt(F(_CHEB_B)).select(x.lt(F(12)).select(x, F(_CHEB_B)), F(_CHEB_B))
    var prod = F(1)
    var y = xr
    comptime for _ in range(10):
        var step = y.gt(F(_CHEB_B))
        y = step.select(y - F(1), y)
        prod = step.select(prod * y, prod)
    var rec = _lgamma_mid[w](y) + slog[w](prod)
    # (d) x >= 12
    var xl = x.ge(F(12)).select(x, F(12))
    var big = _lgamma_stirling[w](xl)
    var res = x.lt(F(_CHEB_A)).select(low, mid)
    res = x.gt(F(_CHEB_B)).select(rec, res)
    res = x.ge(F(12)).select(big, res)
    res = x.eq(F(POS_INF)).select(x, res)
    # non-positive arguments (poles, reflection): libm lgamma_r per lane, rarely taken
    var nonpos = x.le(F(0))
    if nonpos.reduce_or():
        comptime for l in range(w):
            if x[l] <= 0.0:
                var sg = Int32(0)
                res[l] = external_call["lgamma_r", Float64](x[l], Pointer(to=sg))
    return _isnan[w](x).select(x, res)
'''


def prelude() -> str:
    """The Mojo source to splice into the generated header."""
    return (PRELUDE.replace("__CHEB_A__", repr(CHEB_A)).replace("__CHEB_B__", repr(CHEB_B))
            .replace("__CHEB_N__", str(len(CHEB_COEFS)))
            .replace("__CHEB_COEFS__", ", ".join(repr(float(c)) for c in CHEB_COEFS)))


# scalar-op name -> (SIMD implementation, libm per-lane fallback). Templates take (w, arg).
_SIMD = {"exp": "sexp[{w}]({a})", "log": "slog[{w}]({a})", "log1p": "slog1p[{w}]({a})",
         "expm1": "sexpm1[{w}]({a})", "gammaln": "slgamma[{w}]({a})"}
_LIBM = {"exp": "vexp[{w}]({a})", "log": 'vlibm1["log", {w}]({a})', "log1p": 'vlibm1["log1p", {w}]({a})',
         "expm1": 'vlibm1["expm1", {w}]({a})', "gammaln": "vlgamma[{w}]({a})"}


def call(name: str, w: str, a: str) -> str:
    """Mojo expression for transcendental ``name`` applied to SIMD expression ``a`` of width ``w``."""
    return (_LIBM if LIBM else _SIMD)[name].format(w=w, a=a)
